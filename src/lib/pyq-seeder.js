function shuffleOptions(correctOpt, wrongOpts) {
  const all = [
    {
      optionText: correctOpt.text,
      optionTextMr: correctOpt.textMr || correctOpt.text,
      isCorrect: true,
    },
    ...wrongOpts.map((w) => ({
      optionText: w.text,
      optionTextMr: w.textMr || w.text,
      isCorrect: false,
    })),
  ];
  for (let i = all.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [all[i], all[j]] = [all[j], all[i]];
  }
  return all;
}

